#!/usr/bin/env python3
"""Write the Lean files UniformFinite51.lean to UniformFinite109.lean.

The files are in the folder GraphMinor/Thomason of the Lean formalization.
They are made from global_finite_certificate.jsonl, the certificate of
Section 4 of the note uniform_minor_bound.pdf.  For each p the script writes
the row of `GraphMinor.Thomason.Uniform.rowOK`: the density c of the
certificate, integers a and b = 1000 with 2^a <= p^b (so a/b <= log2 p),
and one entry for each order n = R+2, ..., c of a reduced graph, copied from
the certificate.  A uniform entry ["u",k,an,ad] becomes `.u k an ad`, and a
mixed entry ["m",N2,N3,a2n,a2d,a3n,a3d] becomes `.m N2 N3 a2n a2d a3n a3d`.

Lean checks c <= 2.68 p sqrt(log2 p) by 10000 b c^2 <= 71824 a p^2, in
place of the bound c < (16/5) p sqrt(ln p) of the note.  Before writing, the
script runs the same integer tests as `rowOK` and the Lean function
`twoSizeOK` (file UniformCheck.lean), so that a row that Lean would reject
is reported here.  The Lean kernel checks every row again, and the proof
does not depend on this script.

Usage: python3 gen_lean_finite.py OUTDIR
To reproduce the Lean files, take OUTDIR to be GraphMinor/Thomason.
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
B = 1000

def loss_two(n, q, ka, kb, Na, Nb, aN, aD, bN, bD):
    """The total expected loss as one fraction, as the Lean function `lossTwo`."""
    terms = [
        (Na * (2 ** (ka - 1) - 1) * q ** (ka - 1), (n + 1 - ka) ** (ka - 1)),
        (Na * aD, aN),
        (Nb * (2 ** (kb - 1) - 1) * q ** (kb - 1), (n + 1 - kb) ** (kb - 1)),
        (Nb * bD, bN),
        (Na * max(Na - 1, 0) * (aN * q ** ka) ** ka, 2 * (aD * n ** (ka - 1) * (n - ka)) ** ka),
        (Na * Nb * (aN * q ** ka) ** kb, (aD * n ** (ka - 1) * (n - ka)) ** kb),
        (Nb * max(Nb - 1, 0) * (bN * q ** kb) ** kb, 2 * (bD * n ** (kb - 1) * (n - kb)) ** kb),
    ]
    num, den = terms[-1]
    for (a, b) in reversed(terms[:-1]):
        num, den = a * den + num * b, b * den
    return num, den

def two_size_ok(n, q, m, ka, kb, Na, Nb, aN, aD, bN, bD):
    """The integer test of the Lean function `twoSizeOK`."""
    if not (1 <= ka and 1 <= kb and ka < n and kb < n and Na * ka + Nb * kb <= n
            and aN > 0 and aD > 0 and bN > 0 and bD > 0 and m <= Na + Nb):
        return False
    num, den = loss_two(n, q, ka, kb, Na, Nb, aN, aD, bN, bD)
    return num < (Na + Nb + 1 - m) * den

def entry_ok(m, R, n, e):
    q = (n - R) // 2
    if e[0] == 'u':
        k, an, ad = e[1:]
        return two_size_ok(n, q, m, k, 1, n // k, 0, an, ad, 1, 1)
    N2, N3, a2n, a2d, a3n, a3d = e[1:]
    return two_size_ok(n, q, m, 2, 3, N2, N3, a2n, a2d, a3n, a3d)

def log2_num(p):
    """The largest a with 2^a <= p^B."""
    a = 0
    while 2 ** (a + 1) <= p ** B:
        a += 1
    return a

def lean_entry(e):
    return ('.u ' if e[0] == 'u' else '.m ') + ' '.join(str(x) for x in e[1:])

def main(outdir):
    rows = [json.loads(l) for l in open(os.path.join(HERE, 'global_finite_certificate.jsonl'))]
    for row in rows:
        p, c, es = row['p'], row['c'], row['entries']
        R = 25 * c // 67 - 1
        a = log2_num(p)
        assert 4 <= p and 3 <= c and 2 ** a <= p ** B
        assert 10000 * B * c * c <= 71824 * a * p * p, p
        assert p - 2 <= R and R + 1 + len(es) == c
        for i, e in enumerate(es):
            assert entry_ok(p - 2, R, R + 2 + i, e), (p, R + 2 + i)
        lines = ['module', 'public import GraphMinor.Thomason.UniformRows', '',
                 '/-!', f'# Certificate row for `p = {p}`', '',
                 'Generated by `docs/thomason/gen_lean_finite.py` from',
                 '`global_finite_certificate.jsonl`. The kernel evaluates `rowOK`.', '-/', '',
                 'public section', 'namespace GraphMinor.Thomason.Uniform', '',
                 f'/-- The block choices for `p = {p}`, one for each reduced order. -/',
                 f'def finiteRow{p} : List Entry :=']
        body = ',\n    '.join(lean_entry(e) for e in es)
        lines.append('  [' + body + ']')
        lines += ['', f'/-- The certificate row for `p = {p}` passes the integer test. -/',
                  f'theorem finiteRow{p}_ok : rowOK {p} {c} {a} {B} finiteRow{p} = true := by',
                  '  decide +kernel', '', 'end GraphMinor.Thomason.Uniform', '']
        open(os.path.join(outdir, f'UniformFinite{p}.lean'), 'w').write('\n'.join(lines))
        print(p, c, a, len(es))

if __name__ == '__main__':
    main(sys.argv[1])
