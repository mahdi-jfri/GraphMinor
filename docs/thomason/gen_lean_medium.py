#!/usr/bin/env python3
"""Write the Lean files UniformMedium0.lean to UniformMedium6.lean and
UniformMediumRange.lean.

The files are in the folder GraphMinor/Thomason of the Lean formalization.
They are made from medium_log2_certificate.jsonl, which lists intervals
L <= p <= U covering 110 <= p <= 10^44, each with its cells (see
medium_log2_certificate.py).  The script splits the intervals into
consecutive segments of PER intervals and writes one module
UniformMediumJ.lean for segment J.  Each module defines the list of
intervals of its segment as a value of
`List GraphMinor.Thomason.Uniform.Interval` and proves
`segOK s list e = true` by `decide +kernel`, where s and e are the first and
last p of the segment.  The script also writes UniformMediumRange.lean,
which joins the segments.

Before writing, the script runs the exact check of
medium_log2_certificate.py.  The Lean kernel checks every interval again,
and the proof does not depend on this script.

Usage: python3 gen_lean_medium.py OUTDIR
To reproduce the Lean files, take OUTDIR to be GraphMinor/Thomason.
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import medium_log2_certificate as med

PER = 10   # intervals per module

def lean_interval(c):
    cells = ',\n      '.join('⟨' + ', '.join(str(x) for x in cell) + '⟩' for cell in c['cells'])
    return (f"  {{ L := {c['L']},\n"
            f"    U := {c['U']},\n"
            f"    aL := {c['aL']}, aU := {c['aU']},\n"
            f"    sLn := {c['sL'][0]}, sLd := {c['sL'][1]},\n"
            f"    sUn := {c['sU'][0]}, sUd := {c['sU'][1]},\n"
            f"    rn := {c['rho'][0]}, rd := {c['rho'][1]},\n"
            f"    cells := [\n      {cells}] }}")

def module(j, seg):
    s, e = seg[0]['L'], seg[-1]['U']
    body = ',\n'.join(lean_interval(c) for c in seg)
    return f'''module
public import GraphMinor.Thomason.UniformIntervals

/-!
# Interval certificate, part {j}

Generated by `docs/thomason/gen_lean_medium.py` from
`medium_log2_certificate.jsonl`. The intervals cover
`{s} ≤ p ≤ {e}`.
-/

public section
namespace GraphMinor.Thomason.Uniform

/-- The intervals of part {j} of the certificate. -/
def mediumSeg{j} : List Interval := [
{body}]

theorem mediumSeg{j}_ok :
    segOK {s} mediumSeg{j}
      {e} = true := by
  decide +kernel

end GraphMinor.Thomason.Uniform
'''

def range_module(segs):
    imports = '\n'.join(f'import GraphMinor.Thomason.UniformMedium{j}' for j in range(len(segs)))
    lines = []
    for j, seg in enumerate(segs):
        s, e = seg[0]['L'], seg[-1]['U']
        lines.append(f'  · exact exists_interval_of_segOK _ _ _ mediumSeg{j}_ok p (by omega) (by omega)'
                     if j == len(segs) - 1 else
                     f'  by_cases h{j} : p ≤ {e}\n'
                     f'  · exact exists_interval_of_segOK _ _ _ mediumSeg{j}_ok p (by omega) h{j}')
    end = segs[-1][-1]['U']
    return f'''module
public import GraphMinor.Thomason.UniformIntervals
{imports}

/-!
# The interval certificate covers `110 ≤ p ≤ 10 ^ 44`

Generated by `docs/thomason/gen_lean_medium.py`. Each part
`UniformMediumJ.lean` checks a chain of accepted intervals in the kernel;
here we join the chains.
-/

public section
namespace GraphMinor.Thomason.Uniform

/-- Every `110 ≤ p ≤ 10 ^ 44` lies in an accepted interval. -/
theorem exists_interval_of_medium (p : ℕ) (hp1 : 110 ≤ p) (hp2 : p ≤ 10 ^ 44) :
    ∃ I, intervalOK I = true ∧ I.L ≤ p ∧ p ≤ I.U := by
  have hp2' : p ≤ {end} := by
    norm_num at hp2 ⊢; omega
{chr(10).join(lines)}

end GraphMinor.Thomason.Uniform
'''

def main():
    out = sys.argv[1]
    path = os.path.join(HERE, 'medium_log2_certificate.jsonl')
    med.check(path)
    certs = [json.loads(line) for line in open(path)]
    segs = [certs[i:i + PER] for i in range(0, len(certs), PER)]
    for j, seg in enumerate(segs):
        with open(os.path.join(out, f'UniformMedium{j}.lean'), 'w') as f:
            f.write(module(j, seg))
    with open(os.path.join(out, 'UniformMediumRange.lean'), 'w') as f:
        f.write(range_module(segs))
    print(f'wrote {len(segs)} modules')

if __name__ == '__main__':
    main()
